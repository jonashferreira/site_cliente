document.addEventListener("DOMContentLoaded", () => {
    const grid = document.getElementById("pub-grid");
    const paginationContainer = document.getElementById("pub-pagination");
    const searchInput = document.getElementById("pub-search-input");
    const sortSelect = document.getElementById("pub-sort-select");
    const articleModal = document.getElementById("pub-article-view");
    const whiteCard = document.getElementById("art-white-card");
    const backBtn = document.getElementById("pub-back-btn");
    const toggleShareBtn = document.getElementById("toggle-share-btn");
    const shareOptions = document.getElementById("share-options");

    if (!grid) return;

    const ITEMS_PER_PAGE = 6;
    let currentPage = 1;
    let currentFilteredItems = [...PUBLICACOES_DATA];

    function renderPagination(totalItems) {
        if (!paginationContainer) return;

        const totalPages = Math.ceil(totalItems / ITEMS_PER_PAGE);

        if (totalPages <= 1) {
            paginationContainer.innerHTML = "";
            return;
        }

        let html = `
            <button type="button" class="page-btn page-nav" data-page="${currentPage - 1}" ${currentPage === 1 ? "disabled" : ""} aria-label="Página anterior">
                <i class="fas fa-chevron-left"></i>
            </button>
        `;

        for (let i = 1; i <= totalPages; i++) {
            html += `
                <button type="button" class="page-btn ${i === currentPage ? "active" : ""}" data-page="${i}">
                    ${i}
                </button>
            `;
        }

        html += `
            <button type="button" class="page-btn page-nav" data-page="${currentPage + 1}" ${currentPage === totalPages ? "disabled" : ""} aria-label="Próxima página">
                <i class="fas fa-chevron-right"></i>
            </button>
        `;

        paginationContainer.innerHTML = html;

        paginationContainer.querySelectorAll(".page-btn:not([disabled])").forEach(btn => {
            btn.addEventListener("click", () => {
                currentPage = parseInt(btn.getAttribute("data-page"), 10);
                renderCurrentPage();
                const controlsSection = document.querySelector(".pub-controls-section");
                if (controlsSection) {
                    controlsSection.scrollIntoView({ behavior: "smooth", block: "start" });
                }
            });
        });
    }

    function renderCurrentPage() {
        if (currentFilteredItems.length === 0) {
            grid.innerHTML = `<p style="width: 100%; text-align: center; padding: 30px 0; color: #666;">Nenhuma publicação encontrada para o termo pesquisado.</p>`;
            if (paginationContainer) paginationContainer.innerHTML = "";
            return;
        }

        const totalPages = Math.ceil(currentFilteredItems.length / ITEMS_PER_PAGE);
        if (currentPage > totalPages) currentPage = 1;

        const startIndex = (currentPage - 1) * ITEMS_PER_PAGE;
        const pageItems = currentFilteredItems.slice(startIndex, startIndex + ITEMS_PER_PAGE);

        grid.innerHTML = pageItems.map(item => `
            <article class="pub-card" data-id="${item.id}">
                <div>
                    <span class="pub-card-date">${item.data}</span>
                    <h2 class="pub-card-title">${item.resumo}</h2>
                </div>
                <button class="btn-plus-red pub-read-more" data-id="${item.id}">
                    <span class="plus-box">+</span> LEIA MAIS
                </button>
            </article>
        `).join("");

        document.querySelectorAll(".pub-card, .pub-read-more").forEach(el => {
            el.addEventListener("click", (e) => {
                e.stopPropagation();
                const id = el.getAttribute("data-id");
                openArticle(id);
            });
        });

        renderPagination(currentFilteredItems.length);
    }

    function openArticle(id) {
        const article = PUBLICACOES_DATA.find(p => p.id === id);
        if (!article) return;

        document.getElementById("art-date").textContent = article.data;
        document.getElementById("art-title").textContent = article.titulo;
        document.getElementById("art-body").innerHTML = article.conteudo
            .map(p => `<p>${p}</p>`)
            .join("");

        document.getElementById("art-tags").innerHTML = article.tags
            .map(tag => `<span class="art-tag">${tag}</span>`)
            .join(" ");

        const currentUrl = encodeURIComponent(window.location.href);
        const shareText = encodeURIComponent(article.titulo);
        document.getElementById("share-linkedin").href = `https://www.linkedin.com/sharing/share-offsite/?url=${currentUrl}`;
        document.getElementById("share-whatsapp").href = `https://api.whatsapp.com/send?text=${shareText}%20${currentUrl}`;

        if (shareOptions) {
            shareOptions.classList.add("hidden");
        }

        articleModal.classList.remove("hidden");
        articleModal.scrollTop = 0;
        document.body.classList.add("modal-open");
    }

    function closeArticle() {
        articleModal.classList.add("hidden");
        document.body.classList.remove("modal-open");
    }

    backBtn.addEventListener("click", closeArticle);

    articleModal.addEventListener("click", (e) => {
        if (!whiteCard.contains(e.target)) {
            closeArticle();
        }
    });

    document.addEventListener("keydown", (e) => {
        if (e.key === "Escape" && !articleModal.classList.contains("hidden")) {
            closeArticle();
        }
    });

    function filterAndSort() {
        const query = searchInput.value.toLowerCase().trim();
        const sortOrder = sortSelect.value;

        let filtered = PUBLICACOES_DATA.filter(item =>
            item.titulo.toLowerCase().includes(query) ||
            item.resumo.toLowerCase().includes(query) ||
            item.conteudo.some(p => p.toLowerCase().includes(query)) ||
            item.tags.some(t => t.toLowerCase().includes(query))
        );

        if (sortOrder === "oldest") {
            filtered.sort((a, b) => a.timestamp - b.timestamp);
        } else {
            filtered.sort((a, b) => b.timestamp - a.timestamp);
        }

        currentFilteredItems = filtered;
        currentPage = 1;
        renderCurrentPage();
    }

    searchInput.addEventListener("input", filterAndSort);
    sortSelect.addEventListener("change", filterAndSort);

    if (toggleShareBtn && shareOptions) {
        toggleShareBtn.addEventListener("click", () => {
            shareOptions.classList.toggle("hidden");
        });
    }

    document.getElementById("share-copy").addEventListener("click", () => {
        navigator.clipboard.writeText(window.location.href);
        alert("Link da publicação copiado!");
    });

    renderCurrentPage();
});